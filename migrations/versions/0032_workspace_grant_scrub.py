"""Scrub the workspace-creation grant of an offboarded workspace (owner decision,
2026-10-24; ADR-037 amendment).

When workspace offboarding completes, the grant that founded the workspace
keeps no personal data: the founder's normalized email, the founder's user id
(which leads to the email through ``users``) and the operator's free-text note
are set to NULL. What remains is non-personal audit evidence: the immutable
grant id, the consumed workspace (the tombstone) id, who granted it (the
operator label), the timestamps, and when and by which operator it was
scrubbed. No email-derived value (hash or otherwise) is kept anywhere.

- ``scrubbed_at`` / ``scrubbed_by``; the email and founder are NULL exactly on a
  scrubbed row, and only a CONSUMED row can be scrubbed.
- ``workspace_creation_grants_guard`` (BEFORE UPDATE OR DELETE): a scrub is
  allowed only while the consumed workspace is not ACTIVE and changes nothing
  but the three personal columns and the scrub marker; a scrubbed row never
  changes and is never deleted.
- Reuse stays impossible: a scrubbed row stays consumed, and a NULL email never
  matches the creation lookup. The one-open-grant-per-email index covers open
  rows only, so a fresh grant for the same person still works.

Runtime roles still hold no privilege on the table (unchanged).

DOWNGRADE: refused while any grant is scrubbed (the 0022 schema cannot hold a
row without an email); otherwise it restores the 0022 constraints by definition
(under fixed names instead of the generated ones).

Revision ID: 0032_workspace_grant_scrub
Revises: 0031_workspace_offboarding
Create Date: 2026-10-24
"""

from collections.abc import Sequence

from alembic import op

revision: str = "0032_workspace_grant_scrub"
down_revision: str | Sequence[str] | None = "0031_workspace_offboarding"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

T = "workspace_creation_grants"

# The 0022 checks this migration replaces, matched by their definition (their
# names were generated by PostgreSQL), so a renamed or altered check fails the
# upgrade instead of being silently kept.
_EMAIL_0022 = (
    "(email_normalized = lower(btrim(email_normalized)) "
    "AND length(email_normalized) BETWEEN 3 AND 320 "
    "AND position('@' IN email_normalized) > 1)"
)
_FOUNDER_0022 = "((consumed_at IS NULL) = (consumed_by_user_id IS NULL))"

_DROP_BY_DEFINITION = """
DO $$
DECLARE
    v_name text;
BEGIN
    SELECT c.conname INTO STRICT v_name FROM pg_constraint c
        WHERE c.conrelid = 'public.workspace_creation_grants'::regclass AND c.contype = 'c'
          AND pg_get_constraintdef(c.oid) LIKE {pattern};
    EXECUTE format('ALTER TABLE public.workspace_creation_grants DROP CONSTRAINT %I', v_name);
END $$
"""

_GUARD = """
CREATE FUNCTION workspace_creation_grants_guard() RETURNS trigger
    LANGUAGE plpgsql SET search_path = pg_catalog
    AS $$
    BEGIN
        IF OLD.scrubbed_at IS NOT NULL THEN
            RAISE EXCEPTION 'a scrubbed workspace-creation grant never changes'
                USING ERRCODE = 'check_violation';
        END IF;
        IF TG_OP = 'DELETE' THEN
            RETURN OLD;
        END IF;
        IF NEW.scrubbed_at IS NOT NULL THEN
            IF NEW.id IS DISTINCT FROM OLD.id
               OR NEW.granted_by IS DISTINCT FROM OLD.granted_by
               OR NEW.created_at IS DISTINCT FROM OLD.created_at
               OR NEW.expires_at IS DISTINCT FROM OLD.expires_at
               OR NEW.revoked_at IS DISTINCT FROM OLD.revoked_at
               OR NEW.revoked_by IS DISTINCT FROM OLD.revoked_by
               OR NEW.consumed_at IS DISTINCT FROM OLD.consumed_at
               OR NEW.consumed_workspace_id IS DISTINCT FROM OLD.consumed_workspace_id THEN
                RAISE EXCEPTION 'a grant scrub changes only its personal columns'
                    USING ERRCODE = 'check_violation';
            END IF;
            IF OLD.consumed_workspace_id IS NULL
               OR public.workspace_is_active(OLD.consumed_workspace_id) THEN
                RAISE EXCEPTION 'only the grant of an offboarding workspace is scrubbed'
                    USING ERRCODE = 'check_violation';
            END IF;
        END IF;
        RETURN NEW;
    END;
    $$
"""


def upgrade() -> None:
    op.execute(
        f"ALTER TABLE {T} ADD COLUMN scrubbed_at timestamptz, ADD COLUMN scrubbed_by text, "
        f"ADD CONSTRAINT {T}_scrubbed_by_check CHECK "
        "(scrubbed_by IS NULL OR scrubbed_by ~ '^[A-Za-z0-9._-]{1,64}$'), "
        f"ADD CONSTRAINT {T}_scrub_marker_check CHECK "
        "((scrubbed_at IS NULL) = (scrubbed_by IS NULL))"
    )
    op.execute(_DROP_BY_DEFINITION.format(pattern="'%''@''%'"))
    op.execute(_DROP_BY_DEFINITION.format(pattern="'%(consumed_by_user_id IS NULL)%'"))
    op.execute(f"ALTER TABLE {T} ALTER COLUMN email_normalized DROP NOT NULL")
    op.execute(
        f"ALTER TABLE {T} ADD CONSTRAINT {T}_email_check CHECK ("
        f"(scrubbed_at IS NULL AND email_normalized IS NOT NULL AND {_EMAIL_0022}) "
        "OR (scrubbed_at IS NOT NULL AND email_normalized IS NULL))"
    )
    op.execute(
        f"ALTER TABLE {T} ADD CONSTRAINT {T}_founder_check CHECK ("
        f"(scrubbed_at IS NULL AND {_FOUNDER_0022}) "
        "OR (scrubbed_at IS NOT NULL AND consumed_by_user_id IS NULL))"
    )
    op.execute(
        f"ALTER TABLE {T} ADD CONSTRAINT {T}_scrubbed_state_check CHECK ("
        "scrubbed_at IS NULL OR (consumed_at IS NOT NULL AND consumed_workspace_id IS NOT NULL "
        "AND note IS NULL))"
    )
    op.execute(_GUARD)
    op.execute(
        f"CREATE TRIGGER {T}_guard BEFORE UPDATE OR DELETE ON {T} "
        "FOR EACH ROW EXECUTE FUNCTION workspace_creation_grants_guard()"
    )
    op.execute("REVOKE ALL ON FUNCTION workspace_creation_grants_guard() FROM PUBLIC")


def downgrade() -> None:
    op.execute(
        f"""
        DO $$ BEGIN
            IF EXISTS (SELECT 1 FROM {T} WHERE scrubbed_at IS NOT NULL) THEN
                RAISE EXCEPTION '0032 downgrade refused: a workspace-creation grant is '
                    'scrubbed (disposable databases only)' USING ERRCODE = '55000';
            END IF;
        END $$
        """
    )
    op.execute(f"DROP TRIGGER {T}_guard ON {T}")
    op.execute("DROP FUNCTION workspace_creation_grants_guard()")
    op.execute(
        f"ALTER TABLE {T} DROP CONSTRAINT {T}_scrubbed_state_check, "
        f"DROP CONSTRAINT {T}_founder_check, DROP CONSTRAINT {T}_email_check"
    )
    op.execute(f"ALTER TABLE {T} ALTER COLUMN email_normalized SET NOT NULL")
    op.execute(f"ALTER TABLE {T} ADD CONSTRAINT {T}_email_normalized_check CHECK {_EMAIL_0022}")
    op.execute(f"ALTER TABLE {T} ADD CONSTRAINT {T}_founder_0022_check CHECK {_FOUNDER_0022}")
    op.execute(
        f"ALTER TABLE {T} DROP CONSTRAINT {T}_scrub_marker_check, "
        f"DROP CONSTRAINT {T}_scrubbed_by_check, DROP COLUMN scrubbed_by, DROP COLUMN scrubbed_at"
    )
